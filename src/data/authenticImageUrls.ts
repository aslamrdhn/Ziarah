import verifiedSiteImages from './verifiedSiteImages.json';

export interface VerifiedSiteImageMeta {
  url: string;
  author: string;
  license: string;
}

type RawVerifiedImageEntry = string | VerifiedSiteImageMeta;

const rawMap = verifiedSiteImages as Record<string, RawVerifiedImageEntry>;

export const PRE_RESOLVED_AUTHENTIC_IMAGE_META: Record<string, VerifiedSiteImageMeta> = Object.fromEntries(
  Object.entries(rawMap).map(([key, entry]) => {
    if (typeof entry === 'string') {
      return [
        key,
        {
          url: entry,
          author: entry.startsWith('/thumbs/')
            ? 'Arsip Dokumentasi Wikimedia Commons / Tropenmuseum'
            : 'Kontributor Wikimedia Commons',
          license: entry.startsWith('/thumbs/') ? 'Domain Publik / CC BY-SA' : 'CC BY-SA 4.0',
        },
      ];
    }
    return [
      key,
      {
        url: entry.url,
        author: entry.author || 'Kontributor Wikimedia Commons',
        license: entry.license || 'CC BY-SA 4.0',
      },
    ];
  })
);

/**
 * Strictly verified heritage photographs for ziarah sites.
 * Generated by scripts/fetch-verified-images.mjs using isStrictHeritageImage.
 */
export const PRE_RESOLVED_AUTHENTIC_IMAGES: Record<string, string> = Object.fromEntries(
  Object.entries(PRE_RESOLVED_AUTHENTIC_IMAGE_META).map(([key, meta]) => [key, meta.url])
);
